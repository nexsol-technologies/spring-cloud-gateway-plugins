package ch.nexsol.gateway.mcp.server.autoconfigure;

import ch.nexsol.gateway.mcp.server.routes.RouteTools;

import org.springframework.aot.hint.BindingReflectionHintsRegistrar;
import org.springframework.aot.hint.RuntimeHints;
import org.springframework.aot.hint.RuntimeHintsRegistrar;

/**
 * Registers the records the tools answer with, which the server serialises reflectively.
 */
class GatewayMcpRuntimeHints implements RuntimeHintsRegistrar {

	private final BindingReflectionHintsRegistrar bindingRegistrar = new BindingReflectionHintsRegistrar();

	@Override
	public void registerHints(RuntimeHints hints, ClassLoader classLoader) {
		this.bindingRegistrar.registerReflectionHints(hints.reflection(), RouteTools.RouteDescription.class,
				RouteTools.Step.class, RouteTools.FactoryDescription.class);
	}

}
